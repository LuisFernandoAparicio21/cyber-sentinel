"""
sprint_step1_cf.py - Se ejecuta como CF Task dentro de la red de SAP
Crea SECURITY_DATA_FINAL + índices + views + permisos en HANA Cloud
"""
import os, sys
from hdbcli import dbapi

HANA_HOST = os.environ.get("HANA_HOST", "<your-hana-host>.hanacloud.ondemand.com")
HANA_PORT = int(os.environ.get("HANA_PORT", "443"))
HANA_USER = os.environ.get("HANA_USER", "DBADMIN")
HANA_PASSWORD = os.environ["HANA_PASSWORD"]

print("Conectando a HANA Cloud...")
conn = dbapi.connect(address=HANA_HOST, port=HANA_PORT, user=HANA_USER, password=HANA_PASSWORD, encrypt=True)
cursor = conn.cursor()
print("OK Conectado.\n")

STATEMENTS = [
    ("SCHEMA",         'CREATE SCHEMA "SOC_LOGS"'),
    ("TABLE", '''CREATE COLUMN TABLE "SOC_LOGS"."SECURITY_DATA_FINAL" (
    "EVENT_ID" NVARCHAR(50) NOT NULL, "TIMESTAMP" TIMESTAMP,
    "SRC_IP" NVARCHAR(45), "DST_IP" NVARCHAR(45),
    "SRC_PORT" INTEGER, "DST_PORT" INTEGER, "PROTOCOL" NVARCHAR(10),
    "DURATION" DOUBLE, "TOTAL_FWD_PACKETS" INTEGER, "TOTAL_BWD_PACKETS" INTEGER,
    "FLOW_BYTES_PER_S" DOUBLE, "FLOW_PACKETS_PER_S" DOUBLE,
    "FWD_PKT_LEN_MEAN" DOUBLE, "BWD_PKT_LEN_MEAN" DOUBLE,
    "FLAG_SYN" TINYINT, "FLAG_ACK" TINYINT, "FLAG_FIN" TINYINT, "FLAG_RST" TINYINT,
    "LABEL" NVARCHAR(50), "TOTAL_BYTES" BIGINT, "ATTACK_CATEGORY" NVARCHAR(100),
    "IS_ATTACK" TINYINT NOT NULL DEFAULT 0, "DATASET_SOURCE" NVARCHAR(50),
    "PAYLOAD" NCLOB, "INGESTION_TS" TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY ("EVENT_ID")
) PARTITION BY HASH ("EVENT_ID") PARTITIONS 4'''),
    ("IDX_TS",       'CREATE INDEX IDX_FINAL_TS       ON "SOC_LOGS"."SECURITY_DATA_FINAL" ("TIMESTAMP")'),
    ("IDX_ATTACK",   'CREATE INDEX IDX_FINAL_ATTACK   ON "SOC_LOGS"."SECURITY_DATA_FINAL" ("IS_ATTACK","ATTACK_CATEGORY")'),
    ("IDX_SRC_IP",   'CREATE INDEX IDX_FINAL_SRC_IP   ON "SOC_LOGS"."SECURITY_DATA_FINAL" ("SRC_IP")'),
    ("IDX_PROTOCOL", 'CREATE INDEX IDX_FINAL_PROTOCOL ON "SOC_LOGS"."SECURITY_DATA_FINAL" ("PROTOCOL")'),
    ("VIEW_ML", '''CREATE OR REPLACE VIEW "SOC_LOGS"."V_ATTACKS_ML" AS
SELECT "EVENT_ID","TIMESTAMP","SRC_IP","DST_IP","SRC_PORT","DST_PORT","PROTOCOL",
       "DURATION","TOTAL_FWD_PACKETS","TOTAL_BWD_PACKETS","FLOW_BYTES_PER_S","FLOW_PACKETS_PER_S",
       "FWD_PKT_LEN_MEAN","BWD_PKT_LEN_MEAN","FLAG_SYN","FLAG_ACK","FLAG_FIN","FLAG_RST",
       "ATTACK_CATEGORY","IS_ATTACK","DATASET_SOURCE"
FROM "SOC_LOGS"."SECURITY_DATA_FINAL" WHERE "IS_ATTACK" = 1'''),
    ("VIEW_24H", '''CREATE OR REPLACE VIEW "SOC_LOGS"."V_ALERTS_24H" AS
SELECT "EVENT_ID","TIMESTAMP","SRC_IP","DST_IP","PROTOCOL","ATTACK_CATEGORY","PAYLOAD","INGESTION_TS"
FROM "SOC_LOGS"."SECURITY_DATA_FINAL"
WHERE "IS_ATTACK" = 1 AND "TIMESTAMP" >= ADD_SECONDS(CURRENT_TIMESTAMP, -86400)
ORDER BY "TIMESTAMP" DESC'''),
    ("VIEW_STATS", '''CREATE OR REPLACE VIEW "SOC_LOGS"."V_STATS_BY_CATEGORY" AS
SELECT "ATTACK_CATEGORY","DATASET_SOURCE",
       COUNT(*) AS "TOTAL", SUM(TO_BIGINT("IS_ATTACK")) AS "ATTACKS",
       AVG("DURATION") AS "AVG_DURATION", AVG("FLOW_BYTES_PER_S") AS "AVG_BYTES_PER_S"
FROM "SOC_LOGS"."SECURITY_DATA_FINAL"
GROUP BY "ATTACK_CATEGORY","DATASET_SOURCE"'''),
    ("GRANT_ML_V1",   'GRANT SELECT ON "SOC_LOGS"."V_ATTACKS_ML"       TO "ROLE_ML"'),
    ("GRANT_ML_V3",   'GRANT SELECT ON "SOC_LOGS"."V_STATS_BY_CATEGORY" TO "ROLE_ML"'),
    ("GRANT_DASH_V2", 'GRANT SELECT ON "SOC_LOGS"."V_ALERTS_24H"        TO "ROLE_DASHBOARD"'),
    ("GRANT_DASH_V3", 'GRANT SELECT ON "SOC_LOGS"."V_STATS_BY_CATEGORY" TO "ROLE_DASHBOARD"'),
    ("GRANT_BACK_V3", 'GRANT SELECT ON "SOC_LOGS"."V_STATS_BY_CATEGORY" TO "ROLE_BACKEND"'),
    ("GRANT_BACK_T",  'GRANT SELECT, INSERT ON "SOC_LOGS"."SECURITY_DATA_FINAL" TO "ROLE_BACKEND"'),
]

errors = []
for name, sql in STATEMENTS:
    try:
        cursor.execute(sql.strip())
        conn.commit()
        print(f"OK {name}")
    except Exception as e:
        msg = str(e)
        if any(x in msg for x in ["already exists","duplicate","301","386"]):
            print(f"SKIP {name}: ya existe")
        else:
            print(f"ERROR {name}: {msg}")
            errors.append((name, msg))

# Reporte final
cursor.execute("SELECT TABLE_NAME, RECORD_COUNT FROM M_TABLES WHERE SCHEMA_NAME = 'SOC_LOGS'")
for r in cursor.fetchall(): print(f"TABLE {r[0]}: {r[1]} rows")

cursor.execute("SELECT VIEW_NAME FROM VIEWS WHERE SCHEMA_NAME = 'SOC_LOGS'")
for r in cursor.fetchall(): print(f"VIEW  {r[0]}")

cursor.close(); conn.close()

if errors:
    print(f"ERRORES: {errors}")
    sys.exit(1)
print("STEP1 COMPLETO")
